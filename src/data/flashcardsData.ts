/**
 * Helper to pull definitions dynamically from chaptersData.ts if needed,
 * merging with the core curated definitions.
 */
export function getAllDefinitions(): FlashcardDefinition[] {
  return [...CORE_PHYSICS_DEFINITIONS];
}

export function getRandomDefinitions(
  count: number = 10,
  chapterId?: ChapterId | 'all',
  category?: DefinitionCategory | 'all'
): FlashcardDefinition[] {
  let filtered = [...CORE_PHYSICS_DEFINITIONS];

  if (chapterId && chapterId !== 'all') {
    filtered = filtered.filter((d) => d.chapterId === chapterId);
  }

  if (category && category !== 'all') {
    filtered = filtered.filter((d) => d.category === category);
  }

  // Fisher-Yates Shuffle
  const shuffled = [...filtered];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}
